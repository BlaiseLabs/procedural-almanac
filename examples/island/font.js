// each glyph's rows, trimmed to the columns it uses so the text is set proportionally (a space is three wide)
export const GLYPHS = {};
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split(' ');
  let a = 5,
    b = -1;
  for (const r of rows)
    for (let x = 0; x < 5; x++)
      if (r[x] === '#') {
        a = Math.min(a, x);
        b = Math.max(b, x);
      }
  GLYPHS[ch] = rows.map((r) => r.slice(a, b + 1));
}
GLYPHS[' '] = Array(8).fill('...');

/**
 * A line of text as rows of letters for spriteFromRows: each glyph's pixels as the letter given (`ink` for words in
 * backticks, `plain` for the rest), a column of space between glyphs, and every pixel doubled if big.
 * @param {string} text
 * @param {{plain?: string, ink?: string, big?: boolean}} [o]
 * @returns {string[]} eight rows (sixteen if big)
 */
export function textRows(text, o = {}) {
  const plain = o.plain || '#',
    ink = o.ink || '+',
    rows = Array(8).fill('');
  let code = false;
  for (const ch of text) {
    if (ch === '`') {
      code = !code;
      continue;
    }
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let y = 0; y < 8; y++) rows[y] += g[y].replace(/#/g, code ? ink : plain) + '.';
  }
  if (!o.big) return rows;
  const out = [];
  for (const r of rows) {
    const wide = [...r].map((c) => c + c).join('');
    out.push(wide, wide);
  }
  return out;
}
